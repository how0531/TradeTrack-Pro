// 台灣證券交易所 (TWSE) 國定假日休市表
//
// 用途：計算「未創高天數 / maxStagnationDays」等以交易日為單位的指標時，
//      除了排除週六/週日，還需排除這些 TWSE 公告的休市日，
//      否則春節等長假會把停滯天數虛增 5-10 天。
//
// 來源：證交所每年 11-12 月公告隔年「臺灣證券交易所股份有限公司股市開（休）市日期」。
// 維護：每年新行事曆公告後在此檔追加下一年的休市日（一年一筆 ~13 個項目）。
// 範圍：颱風假等臨時休市未包含 — 影響面小且無法事前列表。
// 補班日：證交所在補班週六會照常開市，目前演算法本來就把週六排除，
//        因此補班 Saturday 會被低估，但此情境一年至多 1-2 次、影響有限。

